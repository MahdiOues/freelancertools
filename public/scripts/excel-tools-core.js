function readFile(file, onData) {
  const reader = new FileReader();
  reader.onload = (e) => {
    const data = new Uint8Array(e.target.result);
    const wb = XLSX.read(data, { type: 'array' });
    const ws = wb.Sheets[wb.SheetNames[0]];
    const json = XLSX.utils.sheet_to_json(ws, { defval: '' });
    onData(json);
  };
  reader.readAsArrayBuffer(file);
}

function parseText(text) {
  const lines = text.trim().split('\n').map(l => l.split(/[\t,]+/));
  const headers = lines[0].map(h => h.trim());
  return lines.slice(1).map(row => {
    const obj = {};
    headers.forEach((h, i) => obj[h] = row[i]?.trim() ?? '');
    return obj;
  });
}

function exportXLSX(data, filename, sheetName = 'Sheet1') {
  const ws = XLSX.utils.json_to_sheet(data);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, sheetName);
  XLSX.writeFile(wb, filename);
}

function exportTableXLSX(tableId, filename) {
  const table = document.getElementById(tableId);
  const wb = XLSX.utils.table_to_book(table);
  XLSX.writeFile(wb, filename);
}

function exportPDF(title, tableId, chartCanvasId) {
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'a4' });
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text(title, 40, 50);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text('Generated by FreelancerTools.io', 40, 68);

  let yPos = 90;

  if (chartCanvasId) {
    const canvas = document.getElementById(chartCanvasId);
    if (canvas) {
      const imgData = canvas.toDataURL('image/png');
      doc.addImage(imgData, 'PNG', 40, yPos, 515, 220);
      yPos += 235;
    }
  }

  if (tableId) {
    const table = document.getElementById(tableId);
    if (table) {
      doc.autoTable({
        html: '#' + tableId,
        startY: yPos,
        styles: { fontSize: 8, cellPadding: 4 },
        headStyles: { fillColor: [26, 26, 26], textColor: 255 },
        alternateRowStyles: { fillColor: [248, 248, 246] },
        margin: { left: 40, right: 40 }
      });
    }
  }

  doc.save(title.replace(/\s+/g, '_') + '.pdf');
}

function fmt(n, decimals = 2) {
  return Number(n).toLocaleString('en-US', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals
  });
}

function fmtCurrency(n) {
  return '$' + fmt(n, 2);
}

function fmtPct(n) {
  return fmt(n, 2) + '%';
}
